const ROWS: Record<string, number[]> = {};
for (const [ch, art] of Object.entries(GLYPHS)) {
  ROWS[ch] = art.split('|').map((row) => [...row].reduce((bits, c, i) => bits | (c === '#' ? 1 << i : 0), 0));
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}

/** Draws text with its top-left corner at (x, y). A shadow colour adds a 1-pixel drop shadow. */
export function drawText(fb: Framebuffer, text: string, x: number, y: number, color: Color, scale = 1, shadow?: Color): void {
  if (shadow !== undefined) drawText(fb, text, x + scale, y + scale, shadow, scale);
  let cx = Math.round(x);
  const top = Math.round(y);
  for (const raw of text) {
    const rows = ROWS[raw] ?? ROWS[raw.toUpperCase()] ?? ROWS['?'];
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r];
      if (!bits) continue;
      for (let c = 0; c < GLYPH_W; c++) if (bits & (1 << c)) fb.rect(cx + c * scale, top + r * scale, scale, scale, color);
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
